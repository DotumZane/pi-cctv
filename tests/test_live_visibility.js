const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const html = fs.readFileSync('cctv/dashboard.html', 'utf8');
const handler = html.slice(html.indexOf('function handleLiveVisibilityChange()'), html.indexOf("document.addEventListener('visibilitychange',handleLiveVisibilityChange)"));
const video = {isConnected: true, dataset: {live: 'cam'}, currentTime: 12, readyState: 4, paused: false, srcObject: {}, currentSrc: '', error: null};
const playback = {lastTime: 0, lastProgress: 0, retryTimer: 42, retry: 1};
let reconnects = 0, cleared = 0;
const document = {hidden: false, querySelectorAll: () => [video]};
const context = {document, livePlayback: new WeakMap([[video, playback]]), isHiddenLiveGrid: () => false, scheduleLiveReconnect: () => reconnects++, clearTimeout: () => cleared++, setLiveState: () => {}, Date};
vm.runInNewContext(handler + '\nhandleLiveVisibilityChange()', context);
assert.equal(reconnects, 0, 'healthy streams remain connected');
assert.equal(cleared, 1, 'obsolete retry is cancelled');
assert.equal(playback.lastTime, 12);
playback.retryPending = true;
video.srcObject = null;
vm.runInNewContext(handler + '\nhandleLiveVisibilityChange()', context);
assert.equal(reconnects, 1, 'a disconnected background stream is recovered');
document.hidden = true;
video.error = {};
vm.runInNewContext(handler + '\nhandleLiveVisibilityChange()', context);
assert.equal(reconnects, 1, 'hidden tabs do not reconnect on visibility events');
console.log('Live tab visibility checks passed');
